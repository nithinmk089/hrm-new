/*
    Migration: 002_CreateCompanyOrganizationMasters
    Purpose:
      - Establish the company root for tenant-scoped HRMS data.
      - Create department, office, and designation masters.
    Standards:
      - SQL objects use the hrms schema and PascalCase names.
      - Primary keys are uniqueidentifier values generated by NEWSEQUENTIALID().
      - Company-owned records carry CompanyId.
      - All persisted timestamps use UTC.
      - DeletedAtUtc implements soft deletion.
      - RowVersion supports optimistic concurrency.
*/

CREATE TABLE [hrms].[Companies]
(
    [CompanyId] uniqueidentifier NOT NULL
        CONSTRAINT [DF_Companies_CompanyId] DEFAULT NEWSEQUENTIALID(),
    [CompanyCode] nvarchar(30) NOT NULL,
    [LegalName] nvarchar(200) NOT NULL,
    [DisplayName] nvarchar(150) NOT NULL,
    [TaxRegistrationNumber] nvarchar(50) NULL,
    [CountryCode] char(2) NOT NULL,
    [DefaultCurrencyCode] char(3) NOT NULL,
    [TimeZoneId] nvarchar(100) NOT NULL
        CONSTRAINT [DF_Companies_TimeZoneId] DEFAULT N'UTC',
    [IsActive] bit NOT NULL
        CONSTRAINT [DF_Companies_IsActive] DEFAULT (1),
    [CreatedAtUtc] datetime2(7) NOT NULL
        CONSTRAINT [DF_Companies_CreatedAtUtc] DEFAULT SYSUTCDATETIME(),
    [CreatedByUserId] uniqueidentifier NULL,
    [UpdatedAtUtc] datetime2(7) NULL,
    [UpdatedByUserId] uniqueidentifier NULL,
    [DeletedAtUtc] datetime2(7) NULL,
    [DeletedByUserId] uniqueidentifier NULL,
    [RowVersion] rowversion NOT NULL,
    CONSTRAINT [PK_Companies] PRIMARY KEY CLUSTERED ([CompanyId]),
    CONSTRAINT [CK_Companies_CompanyCode_NotBlank]
        CHECK (LEN(LTRIM(RTRIM([CompanyCode]))) > 0),
    CONSTRAINT [CK_Companies_LegalName_NotBlank]
        CHECK (LEN(LTRIM(RTRIM([LegalName]))) > 0),
    CONSTRAINT [CK_Companies_DisplayName_NotBlank]
        CHECK (LEN(LTRIM(RTRIM([DisplayName]))) > 0)
);
GO

CREATE UNIQUE INDEX [UX_Companies_CompanyCode_Active]
    ON [hrms].[Companies] ([CompanyCode])
    WHERE [DeletedAtUtc] IS NULL;
GO

CREATE TABLE [hrms].[Departments]
(
    [DepartmentId] uniqueidentifier NOT NULL
        CONSTRAINT [DF_Departments_DepartmentId] DEFAULT NEWSEQUENTIALID(),
    [CompanyId] uniqueidentifier NOT NULL,
    [DepartmentCode] nvarchar(30) NOT NULL,
    [DepartmentName] nvarchar(150) NOT NULL,
    [Description] nvarchar(500) NULL,
    [ParentDepartmentId] uniqueidentifier NULL,
    [IsActive] bit NOT NULL
        CONSTRAINT [DF_Departments_IsActive] DEFAULT (1),
    [CreatedAtUtc] datetime2(7) NOT NULL
        CONSTRAINT [DF_Departments_CreatedAtUtc] DEFAULT SYSUTCDATETIME(),
    [CreatedByUserId] uniqueidentifier NULL,
    [UpdatedAtUtc] datetime2(7) NULL,
    [UpdatedByUserId] uniqueidentifier NULL,
    [DeletedAtUtc] datetime2(7) NULL,
    [DeletedByUserId] uniqueidentifier NULL,
    [RowVersion] rowversion NOT NULL,
    CONSTRAINT [PK_Departments] PRIMARY KEY CLUSTERED ([DepartmentId]),
    CONSTRAINT [UQ_Departments_Company_Department]
        UNIQUE ([CompanyId], [DepartmentId]),
    CONSTRAINT [FK_Departments_Companies]
        FOREIGN KEY ([CompanyId]) REFERENCES [hrms].[Companies] ([CompanyId]),
    CONSTRAINT [FK_Departments_ParentDepartment]
        FOREIGN KEY ([CompanyId], [ParentDepartmentId])
        REFERENCES [hrms].[Departments] ([CompanyId], [DepartmentId]),
    CONSTRAINT [CK_Departments_DepartmentCode_NotBlank]
        CHECK (LEN(LTRIM(RTRIM([DepartmentCode]))) > 0),
    CONSTRAINT [CK_Departments_DepartmentName_NotBlank]
        CHECK (LEN(LTRIM(RTRIM([DepartmentName]))) > 0),
    CONSTRAINT [CK_Departments_NoSelfParent]
        CHECK ([ParentDepartmentId] IS NULL OR [ParentDepartmentId] <> [DepartmentId])
);
GO

CREATE UNIQUE INDEX [UX_Departments_Company_Code_Active]
    ON [hrms].[Departments] ([CompanyId], [DepartmentCode])
    WHERE [DeletedAtUtc] IS NULL;
GO

CREATE INDEX [IX_Departments_Company_Parent]
    ON [hrms].[Departments] ([CompanyId], [ParentDepartmentId])
    INCLUDE ([DepartmentCode], [DepartmentName], [IsActive])
    WHERE [DeletedAtUtc] IS NULL;
GO

